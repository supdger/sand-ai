<?php

declare(strict_types=1);

/**
 * Assemble the SandAI fresh-install lifecycle SQL.
 *
 * install.sql is a generated artifact. Its only sources are
 * tools/resources/install-prelude.pgsql (the collision preflight plus the
 * migration ledger table) and every plugin/sand-ai/migrations/main-app/*.pgsql
 * migration, applied in ascending file-name order. Each migration body is
 * embedded verbatim and followed by its own ledger row, whose checksum is the
 * sha256 digest of the migration file itself, so a fresh install registers the
 * same ledger state that update.sql expects from an upgraded database.
 *
 * Default and --check compare the assembled bytes with the committed
 * install.sql without writing. Only --write replaces the committed file.
 */

const SAND_AI_INSTALL_HEADER = <<<'HEADER'
-- Generated by tools/build-install-sql.php from tools/resources/install-prelude.pgsql
-- and plugin/sand-ai/migrations/main-app/*.pgsql. Do not edit by hand; re-run
-- `php tools/build-install-sql.php --write` after changing a migration source.

HEADER;

/**
 * Read a required source file as a string.
 */
function sandAiReadSource(string $path): string
{
    if (!is_file($path) || is_link($path)) {
        throw new RuntimeException('缺少生成源文件：' . $path);
    }
    $contents = file_get_contents($path);
    if (!is_string($contents)) {
        throw new RuntimeException('无法读取生成源文件：' . $path);
    }

    return $contents;
}

/**
 * Enumerate the migration sources in the exact order install.sql applies them.
 *
 * @return list<string> absolute migration paths sorted by file name
 */
function sandAiMigrationSources(string $root): array
{
    $directory = $root . '/plugin/sand-ai/migrations/main-app';
    $matches = glob($directory . '/*.pgsql');
    if ($matches === false || $matches === []) {
        throw new RuntimeException('迁移源目录为空：' . $directory);
    }
    $sources = [];
    foreach ($matches as $path) {
        if (!is_file($path) || is_link($path)) {
            throw new RuntimeException('迁移源必须是普通文件：' . $path);
        }
        $version = basename($path, '.pgsql');
        if (preg_match('/\A[0-9]{12}_[a-z0-9_]+\z/D', $version) !== 1) {
            throw new RuntimeException('迁移文件名不符合 <12位时间戳>_<小写标识> 约定：' . $path);
        }
        $sources[] = $path;
    }
    sort($sources, SORT_STRING);

    return $sources;
}

/**
 * Assemble the full install.sql payload.
 */
function sandAiBuildInstallSql(string $root): string
{
    $payload = SAND_AI_INSTALL_HEADER . sandAiReadSource($root . '/tools/resources/install-prelude.pgsql');
    if (!str_ends_with($payload, ");\n")) {
        throw new RuntimeException('install 前导段必须以迁移账本表定义结尾');
    }
    foreach (sandAiMigrationSources($root) as $path) {
        $version = basename($path, '.pgsql');
        $checksum = hash_file('sha256', $path);
        if (!is_string($checksum)) {
            throw new RuntimeException('无法计算迁移摘要：' . $path);
        }
        $body = rtrim(sandAiReadSource($path), "\n");
        if ($body === '') {
            throw new RuntimeException('迁移内容为空：' . $path);
        }
        if (preg_match('/^\s*(?:BEGIN|COMMIT|ROLLBACK)\s*;/mi', $body) === 1) {
            throw new RuntimeException('迁移不得自带事务边界，事务由 install.sql 统一持有：' . $path);
        }
        if (str_contains($body, 'sand_ai_schema_migration (version')
            || str_contains($body, 'sand_ai_schema_migration(version')) {
            throw new RuntimeException('迁移不得自行写入账本，账本行由生成器追加：' . $path);
        }
        $payload .= "\n-- Migration {$version} (sha256 {$checksum})\n"
            . $body . "\n"
            . "\nINSERT INTO sand_ai_schema_migration (version, checksum, applied_time)"
            . " VALUES ('{$version}', '{$checksum}', CURRENT_TIMESTAMP(0));\n";
    }

    return $payload . "\nCOMMIT;\n";
}

/**
 * Report the first differing line between the committed and assembled payload.
 */
function sandAiFirstDifference(string $current, string $generated): string
{
    $currentLines = explode("\n", $current);
    $generatedLines = explode("\n", $generated);
    $total = max(count($currentLines), count($generatedLines));
    for ($index = 0; $index < $total; ++$index) {
        $left = $currentLines[$index] ?? '<缺失>';
        $right = $generatedLines[$index] ?? '<缺失>';
        if ($left !== $right) {
            return sprintf("第 %d 行\n  committed: %s\n  generated: %s", $index + 1, $left, $right);
        }
    }

    return '无行级差异（仅长度不同）';
}

$options = getopt('', ['check', 'write']);
if (isset($options['check'], $options['write'])) {
    throw new RuntimeException('只能选择 --check 或 --write');
}
$root = dirname(__DIR__);
$target = $root . '/install.sql';
$generated = sandAiBuildInstallSql($root);

if (isset($options['write'])) {
    if (file_put_contents($target, $generated) === false) {
        throw new RuntimeException('写入失败：' . $target);
    }
    echo 'build-install-sql written ' . strlen($generated) . " bytes\n";
    exit(0);
}

$current = is_file($target) ? sandAiReadSource($target) : '';
if ($current === $generated) {
    echo 'build-install-sql check ok ' . strlen($generated) . " bytes\n";
    exit(0);
}
fwrite(STDERR, "install.sql 与生成结果不一致：\n" . sandAiFirstDifference($current, $generated) . "\n");
exit(1);
