-- Called only after the fixed published schema has been created in pg_temp.
-- This function does not copy, decrypt or expose legacy content.
CREATE FUNCTION pg_temp.sand_ai_public010_check(expected_snapshot jsonb)
RETURNS void LANGUAGE plpgsql AS $public010_guard$
DECLARE
    names constant text[] := ARRAY[
        'sand_ai_provider','sand_ai_model','sand_ai_model_deployment','sand_ai_config_revision',
        'sand_ai_invocation','sand_ai_usage','sand_ai_audit_log','sand_ai_file','sand_ai_file_parse',
        'sand_ai_source_block','sand_ai_capability_profile','sand_ai_capability_route',
        'sand_ai_task_run','sand_ai_task_step'
    ];
    name text;
    actual oid;
    reference oid;
    seq oid;
    refseq oid;
    columns_actual jsonb;
    columns_reference jsonb;
    constraints_actual jsonb;
    constraints_reference jsonb;
    indexes_actual jsonb;
    indexes_reference jsonb;
    item jsonb;
    row_count text;
    rows_sha256 text;
    sequence_last_value text;
    sequence_is_called boolean;
BEGIN
    IF current_schema() <> 'public' OR current_user <> session_user THEN
        RAISE EXCEPTION 'Public 0.1.0 bridge requires the public schema and a direct object-owner connection';
    END IF;
    IF expected_snapshot IS NOT NULL AND (
        jsonb_typeof(expected_snapshot) <> 'array' OR jsonb_array_length(expected_snapshot) <> 14
        OR (SELECT count(DISTINCT value->>'table') FROM jsonb_array_elements(expected_snapshot)) <> 14
        OR EXISTS (SELECT 1 FROM jsonb_array_elements(expected_snapshot) WHERE NOT (value->>'table'=ANY(names)))
    ) THEN
        RAISE EXCEPTION 'Public 0.1.0 backup snapshot must contain exactly the fourteen published tables';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname='public'
          AND (c.relname::text LIKE 'sand_ai_%' OR c.relname::text LIKE 'idx_sand_ai_%'
            OR c.relname::text LIKE 'ix_sand_ai_%' OR c.relname::text LIKE 'uk_sand_ai_%'
            OR c.relname::text LIKE 'uq_sand_ai_%')
          AND c.relname <> 'sand_ai_public010_upgrade'
          AND NOT EXISTS (SELECT 1 FROM pg_class r WHERE r.relnamespace=pg_my_temp_schema() AND r.relname=c.relname)
    ) OR EXISTS (
        SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
        WHERE n.nspname='public' AND p.proname::text LIKE 'sand_ai_%'
    ) OR EXISTS (
        SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace
        WHERE n.nspname='public' AND t.typname::text LIKE 'sand_ai_%'
          AND t.typrelid=0 AND t.typelem=0
    ) THEN
        RAISE EXCEPTION 'Unrecognized SandAI objects; this bridge accepts only the published 0.1.0 profile';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname='sand_ai_public010_archive') THEN
        RAISE EXCEPTION 'Public 0.1.0 archive already exists; use the original candidate recovery or backup restore';
    END IF;
    FOREACH name IN ARRAY names||ARRAY['sand_ai_public010_upgrade'] LOOP
        actual := to_regclass(format('public.%I',name));
        reference := to_regclass(format('pg_temp.%I',name));
        IF name='sand_ai_public010_upgrade' AND actual IS NULL THEN
            CONTINUE;
        END IF;
        IF actual IS NULL OR reference IS NULL OR NOT EXISTS (
            SELECT 1 FROM pg_class WHERE oid=actual AND relkind='r' AND relpersistence='p'
              AND relowner=(SELECT oid FROM pg_roles WHERE rolname=current_user)
              AND NOT relispartition AND NOT relrowsecurity AND NOT relforcerowsecurity
              AND relacl IS NULL AND reloptions IS NULL AND relreplident='d'
        ) OR EXISTS (SELECT 1 FROM pg_inherits WHERE inhrelid=actual OR inhparent=actual)
          OR EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid=actual AND NOT tgisinternal)
          OR EXISTS (SELECT 1 FROM pg_rewrite WHERE ev_class=actual)
          OR EXISTS (SELECT 1 FROM pg_policy WHERE polrelid=actual)
          OR EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid=actual AND attacl IS NOT NULL)
          OR EXISTS (SELECT 1 FROM pg_depend WHERE classid='pg_class'::regclass AND objid=actual AND deptype='e') THEN
            RAISE EXCEPTION 'Public 0.1.0 table ownership or dependencies do not match: %',name;
        END IF;
        EXECUTE format('LOCK TABLE public.%I IN ACCESS EXCLUSIVE MODE',name);
        SELECT jsonb_agg(jsonb_build_array(a.attnum,a.attname,a.atttypid,a.atttypmod,a.attnotnull,
            a.attidentity,a.attgenerated,a.attcollation,pg_get_expr(d.adbin,d.adrelid)) ORDER BY a.attnum)
        INTO columns_actual FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
        WHERE a.attrelid=actual AND a.attnum>0 AND NOT a.attisdropped;
        SELECT jsonb_agg(jsonb_build_array(a.attnum,a.attname,a.atttypid,a.atttypmod,a.attnotnull,
            a.attidentity,a.attgenerated,a.attcollation,pg_get_expr(d.adbin,d.adrelid)) ORDER BY a.attnum)
        INTO columns_reference FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
        WHERE a.attrelid=reference AND a.attnum>0 AND NOT a.attisdropped;
        SELECT jsonb_agg(jsonb_build_array(conname,contype,conkey,confkey,condeferrable,condeferred,convalidated,
            regexp_replace(pg_get_constraintdef(oid,false),'(public|pg_temp_[0-9]+)\.','','g')) ORDER BY conname)
        INTO constraints_actual FROM pg_constraint WHERE conrelid=actual;
        SELECT jsonb_agg(jsonb_build_array(conname,contype,conkey,confkey,condeferrable,condeferred,convalidated,
            regexp_replace(pg_get_constraintdef(oid,false),'(public|pg_temp_[0-9]+)\.','','g')) ORDER BY conname)
        INTO constraints_reference FROM pg_constraint WHERE conrelid=reference;
        SELECT jsonb_agg(jsonb_build_array(c.relname,i.indisvalid,i.indisready,i.indisunique,i.indisprimary,
            regexp_replace(pg_get_indexdef(c.oid),'(public|pg_temp_[0-9]+)\.','','g'),c.reloptions) ORDER BY c.relname)
        INTO indexes_actual FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid WHERE i.indrelid=actual;
        SELECT jsonb_agg(jsonb_build_array(c.relname,i.indisvalid,i.indisready,i.indisunique,i.indisprimary,
            regexp_replace(pg_get_indexdef(c.oid),'(public|pg_temp_[0-9]+)\.','','g'),c.reloptions) ORDER BY c.relname)
        INTO indexes_reference FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid WHERE i.indrelid=reference;
        IF columns_actual IS DISTINCT FROM columns_reference
          OR constraints_actual IS DISTINCT FROM constraints_reference OR indexes_actual IS DISTINCT FROM indexes_reference
          OR EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid=actual AND attnum>0 AND attisdropped) THEN
            RAISE EXCEPTION 'Public 0.1.0 schema does not match the fixed published table: %',name;
        END IF;
        -- External foreign keys and views would continue resolving the archived
        -- objects. Refuse them instead of silently changing their meaning.
        IF EXISTS (
            SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
            WHERE c.confrelid=actual AND NOT (t.relnamespace='public'::regnamespace AND t.relname=ANY(names))
        ) OR EXISTS (
            SELECT 1 FROM pg_depend d WHERE d.refclassid='pg_class'::regclass AND d.refobjid=actual
              AND NOT (
                (d.classid='pg_class'::regclass AND (
                    EXISTS (SELECT 1 FROM pg_index WHERE indexrelid=d.objid AND indrelid=actual)
                    OR EXISTS (SELECT 1 FROM pg_depend owned WHERE owned.classid='pg_class'::regclass
                        AND owned.objid=d.objid AND owned.refclassid='pg_class'::regclass
                        AND owned.refobjid=actual AND owned.deptype='i')))
                OR (d.classid='pg_constraint'::regclass AND EXISTS (
                    SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
                    WHERE c.oid=d.objid AND t.relnamespace='public'::regnamespace
                      AND (c.conrelid=actual OR t.relname=ANY(names))))
                OR (d.classid='pg_attrdef'::regclass AND EXISTS (
                    SELECT 1 FROM pg_attrdef WHERE oid=d.objid AND adrelid=actual))
                OR (d.classid='pg_type'::regclass AND EXISTS (
                    SELECT 1 FROM pg_type WHERE oid=d.objid AND typrelid=actual))
                OR (d.classid='pg_trigger'::regclass AND EXISTS (
                    SELECT 1 FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid
                    WHERE t.oid=d.objid AND t.tgisinternal AND c.relnamespace='public'::regnamespace AND c.relname=ANY(names)))
              )
        ) OR EXISTS (
            SELECT 1 FROM pg_depend d JOIN pg_type row_type ON row_type.typrelid=actual
            WHERE d.refclassid='pg_type'::regclass AND d.refobjid IN (row_type.oid,row_type.typarray)
              AND NOT ((d.classid='pg_type'::regclass AND d.objid=row_type.typarray)
                OR (d.classid='pg_class'::regclass AND d.objid=actual))
        ) THEN
            RAISE EXCEPTION 'External dependency prevents preserving the published table: %',name;
        END IF;
        IF name='sand_ai_public010_upgrade' THEN
            CONTINUE;
        END IF;
        seq := pg_get_serial_sequence(format('public.%I',name),'id')::regclass;
        refseq := pg_get_serial_sequence(format('pg_temp.%I',name),'id')::regclass;
        IF seq IS NULL OR refseq IS NULL OR NOT EXISTS (
            SELECT 1 FROM pg_sequence s JOIN pg_class c ON c.oid=s.seqrelid
            JOIN pg_sequence r ON r.seqrelid=refseq
            WHERE s.seqrelid=seq AND c.relnamespace='public'::regnamespace
              AND c.relowner=(SELECT oid FROM pg_roles WHERE rolname=current_user) AND c.relacl IS NULL
              AND c.relname=name||'_id_seq'
              AND ROW(s.seqtypid,s.seqstart,s.seqincrement,s.seqmax,s.seqmin,s.seqcache,s.seqcycle)
                =ROW(r.seqtypid,r.seqstart,r.seqincrement,r.seqmax,r.seqmin,r.seqcache,r.seqcycle)
        ) OR EXISTS (
            SELECT 1 FROM pg_depend d WHERE d.refclassid='pg_class'::regclass AND d.refobjid=seq
              AND NOT (d.classid='pg_class'::regclass AND d.objid=actual)
        ) THEN
            RAISE EXCEPTION 'Public 0.1.0 identity sequence does not match: %',name;
        END IF;
        IF expected_snapshot IS NOT NULL THEN
            SELECT value INTO item FROM jsonb_array_elements(expected_snapshot) WHERE value->>'table'=name;
            EXECUTE format(
                'SELECT count(*)::text, encode(sha256(convert_to(coalesce(string_agg(encode(sha256(convert_to(to_jsonb(t)::text,''UTF8'')),''hex''),'''' ORDER BY id),''''),''UTF8'')),''hex'') FROM public.%I t',
                name) INTO row_count,rows_sha256;
            EXECUTE format('SELECT last_value::text,is_called FROM %s',seq::regclass) INTO sequence_last_value,sequence_is_called;
            IF item->>'row_count' IS DISTINCT FROM row_count OR item->>'rows_sha256' IS DISTINCT FROM rows_sha256
              OR item->>'sequence_last_value' IS DISTINCT FROM sequence_last_value
              OR (item->>'sequence_is_called')::boolean IS DISTINCT FROM sequence_is_called THEN
                RAISE EXCEPTION 'Public 0.1.0 data or sequence changed after the protected backup: %',name;
            END IF;
        END IF;
    END LOOP;
END
